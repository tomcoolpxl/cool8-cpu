def face_loops():
    """Each face's boundary loop, walked from the edge table. The laser
    line (20-21) hangs off faces 0 and 11 as a spur -- an edge with a
    degree-1 endpoint -- and spurs bound no area, so they are pruned
    before the walk."""
    loops = []
    for face in range(13):
        es = [list(EDGES[e]) for e in range(38)
              if EDGE_FACES[e] != (9, 9) and face in EDGE_FACES[e]]
        while True:
            deg = {}
            for a, b in es:
                deg[a] = deg.get(a, 0) + 1
                deg[b] = deg.get(b, 0) + 1
            drop = [e for e in es if deg[e[0]] == 1 or deg[e[1]] == 1]
            if not drop:
                break
            es = [e for e in es if e not in drop]
        assert len(es) >= 3, "face %d has no loop" % face
        adj = {}
        for a, b in es:
            adj.setdefault(a, []).append(b)
            adj.setdefault(b, []).append(a)
        assert all(len(v) == 2 for v in adj.values()), \
            "face %d boundary is not one cycle" % face
        start = es[0][0]
        loop, prev = [start], None
        while True:
            nxt = [n for n in adj[loop[-1]] if n != prev]
            prev = loop[-1]
            loop.append(nxt[0])
            if loop[-1] == start:
                break
        loops.append(loop[:-1])
    return loops


