def _sub(a, b):
    return tuple(x - y for x, y in zip(a, b))


def _cross(a, b):
    return (a[1] * b[2] - a[2] * b[1], a[2] * b[0] - a[0] * b[2], a[0] * b[1] - a[1] * b[0])


def _dot(a, b):
    return sum(x * y for x, y in zip(a, b))


@functools.lru_cache(maxsize=None)
def act_model(rates=(YAWR, PITCHR, ROLLR), turn_in=HYST):
    """What the compiled COBRAs are built from -- the model, the tables,
    each face's normal and threshold -- checked against the arithmetic
    the program does, over the first 4,096 frames of the tumble at these
    rates and a grid of every pose. sim/test_action.py holds the programs
    to it."""
    loops = face_loops()
    V = [tuple(max(-127, min(127, c)) for c in v) for v in VERTS]

    # a triangle per face: the loop's three vertices spanning the most
    # area, wound so its normal is the published outward one
    tris = []
    for f, lp in enumerate(loops):
        best, tri = -1, None
        for i in range(len(lp)):
            for j in range(i + 1, len(lp)):
                for k in range(j + 1, len(lp)):
                    a, b, c = VERTS[lp[i]], VERTS[lp[j]], VERTS[lp[k]]
                    n = _cross(_sub(b, a), _sub(c, a))
                    if _dot(n, n) > best:
                        best, tri = _dot(n, n), (lp[i], lp[j], lp[k])
        a, b, c = (VERTS[t] for t in tri)
        if _dot(_cross(_sub(b, a), _sub(c, a)), FACES[f]) < 0:
            tri = (tri[0], tri[2], tri[1])
        tris.append(tri)

    sn = [int(round(127 * math.sin(2 * math.pi * i / SINES))) for i in range(SINES)]
    rz = []
    for i in range(ZBINS):
        dep = DIST + 2 * (i - ZBIAS) + 1
        r = int(round(256.0 * FOCAL / dep))
        assert 1 <= r <= 255, "the reciprocal outgrew a byte at bin %d: %d" % (i, r)
        rz.append(r)

    def inside(*vals):
        assert all(-32768 <= q <= 32767 for q in vals), "an INT overflowed: %s" % (vals,)

    def r7(x):
        """(x + 64) >> 7: an INT shift floors, so 64 first rounds"""
        inside(x + 64)
        return (x + 64) >> 7

    def matrix(ya, pa, ra):
        """Matrix(): roll x pitch x yaw from the table, each product of
        two brought back to 127 a unit, rounded"""
        q = SINES // 4
        sa, ca = sn[ya], sn[(ya + q) % SINES]
        sb, cb = sn[pa], sn[(pa + q) % SINES]
        sc, cc = sn[ra], sn[(ra + q) % SINES]
        t, u = r7(sb * sa), r7(sb * ca)
        m = [[r7(cc * ca - sc * t), -r7(sc * cb), r7(cc * sa + sc * u)],
             [r7(sc * ca + cc * t), r7(cc * cb), r7(sc * sa - cc * u)],
             [-r7(cb * sa), sb, r7(cb * ca)]]
        assert all(-127 <= e <= 127 for row in m for e in row)
        return m

    biased = [0]

    def project(m):
        """Transform(): the screen coordinates, as the assembly makes them"""
        pts = []
        for v in V:
            X, Y, Z = (sum(m[r][j] * v[j] for j in range(3)) for r in range(3))
            inside(X, Y, Z)
            if biased[0] < 2000:            # the biased route, modulo 65,536
                biased[0] += 1
                for r, q in enumerate((X, Y, Z)):
                    acc = (sum((m[r][j] + 128) * (v[j] + 128) for j in range(3))
                           - (128 * sum(m[r]) + 49152) - 128 * sum(v)) & 0xFFFF
                    assert acc == q & 0xFFFF, "the bias does not come back off"
            idx = (Z >> 8) + ZBIAS
            assert 0 <= idx < ZBINS, "depth bin %d" % idx
            r = rz[idx]
            ox, oy = ((abs(X) >> 7) * r) >> 8, ((abs(Y) >> 7) * r) >> 8
            sx = CX + ox if X >= 0 else CX - ox
            sy = CY - oy if Y >= 0 else CY + oy
            assert 0 <= sx <= 255 and 0 <= sy <= 239, "off the screen: %d,%d" % (sx, sy)
            pts.append((sx, sy))
        return pts

    def area4(pts, tri):
        """a face's triangle's area on the screen, differences halved,
        INT >> flooring: what Faces() is held to where it is decisive"""
        (xa, ya), (xb, yb), (xc, yc) = (pts[t] for t in tri)
        return ((xb - xa) >> 1) * ((yc - ya) >> 1) - ((yb - ya) >> 1) * ((xc - xa) >> 1)

    # **the faces, by their normals** (Faces()). A face is turned to the
    # viewer when the eye is on the outer side of its plane, and after
    # the rotation that is one comparison: the rotated normal's z against
    # a threshold of the face's own, which is its plane's distance from
    # the ship's centre as seen from DIST away. The normal is not the
    # published one -- those are hand-rounded, degrees off their faces
    # (the cobra.bas notes above) -- but the face's own triangle's, from
    # the vertices the program draws, 127 long so a component is a byte.
    #
    # In Transform's units a coordinate is 127 of the model's and the eye
    # is at Z = -128 DIST (depth is DIST + Z / 128), so n.(eye - P) > 0 is
    # -128 DIST (Mn)z / 127 - 127 n.c > 0 for a point c of the plane: the
    # face shows when (Mn)z < -127^2 n.c / (128 DIST), which is T.
    fn = []
    for a, b, c in tris:
        n = _cross(_sub(V[b], V[a]), _sub(V[c], V[a]))
        s = 127.0 / math.sqrt(_dot(n, n))
        n = tuple(int(round(q * s)) for q in n)
        cen = [(V[a][j] + V[b][j] + V[c][j]) / 3.0 for j in range(3)]
        fn.append((n, int(round(-127 * 127 * _dot(n, cen) / (128.0 * DIST)))))

    def facing(m):
        """Faces(): each face's (Mn)z - T, negative when it is turned to
        the viewer, by the biased route the assembly takes"""
        out = []
        for n, T in fn:
            q = sum(m[2][j] * n[j] for j in range(3)) - T
            inside(q)
            acc = (sum((m[2][j] + 128) * (n[j] + 128) for j in range(3))
                   - (128 * sum(m[2]) + 49152) - (128 * sum(n) + T)) & 0xFFFF
            assert acc == q & 0xFFFF, "the bias does not come back off a normal"
            out.append(q)
        return out

    # **the triangles on the screen**, wound so a face turned to the
    # viewer has a positive area there -- which way that is, measured
    # far from edge-on rather than assumed. The program has no use for
    # them; the checks below and sim/test_action.py compare the cull with
    # the picture through them.
    eye = (0, 0, -128 * DIST)
    agree = against = 0
    for ya in range(0, SINES, SINES // 8):
        for pa in range(0, SINES, SINES // 8):
            for ra in range(0, SINES, SINES // 8):
                m = matrix(ya, pa, ra)
                pts = project(m)
                for t, q in zip(tris, facing(m)):
                    ar = area4(pts, t)
                    if abs(ar) >= 64:
                        if (ar > 0) == (q < 0):
                            agree += 1
                        else:
                            against += 1
    scr = tris if agree >= against else [(a, c, b) for a, b, c in tris]

    # **the tumble itself**: its first 4,096 frames, as the loop steps
    # the angles, culled and listed as the program does -- no edge may
    # flicker, off for a frame and on again -- and then a grid of every
    # pose: each vertex on the screen, each face's decision against its
    # plane in floating point (wrong only within EDGEON degrees of edge-on)
    # and against its triangle on the screen (only where the area, whose
    # sign the rounding of the corners makes unreliable near zero -- the
    # reason for the normals -- is within SURE)
    #
    # **Faces() has HYST of hysteresis, and this is why**: without it
    # edges flickered here, of two kinds -- a face crossing edge-on in a
    # frame that moved it less than the matrix's rounding (-5, then +5),
    # and an edge whose two faces are both within a degree of edge-on
    # for one frame as one turns away and the other turns in. A face
    # turned to the viewer stays so until (Mn)z - T is HYST past zero,
    # and one turned away turns in only HYST short of it.
    assert HYST == 256, "Faces() adds and takes HYST in the high byte"
    ang = [0, 0, 0]
    fv = [False] * 13
    vis, pix, qs, loose = [], [], [], []
    sure, tilt = 0, 0.0
    for fr in range(4096):
        ang = [(a + d) & 0xFFFF for a, d in zip(ang, rates)]
        m = matrix(*(a * SINES >> 16 for a in ang))
        pts = project(m)
        qs.append(facing(m))
        fv = [q - HYST < 0 if was else q + turn_in < 0 for q, was in zip(qs[-1], fv)]
        for t, v in zip(scr, fv):
            ar = area4(pts, t)
            if (ar > 0) != v:
                sure = max(sure, abs(ar))
        es = [e for e in range(38) if fv[EDGE_FACES[e][0]] or fv[EDGE_FACES[e][1]]]
        vis.append(set(es))
        pix.append(sum(max(abs(pts[EDGES[e][0]][0] - pts[EDGES[e][1]][0]),
                           abs(pts[EDGES[e][0]][1] - pts[EDGES[e][1]][1])) + 1 for e in es))
        deg = {}
        for e in es:
            for v in EDGES[e]:
                deg[v] = deg.get(v, 0) + 1
        loose += [(fr, v, [e for e in es if v in EDGES[e]], fv) for v, d in deg.items()
                  if d == 1 and v not in (20, 21)]
    # **the picture closes**: a face turned to the viewer brings its whole
    # boundary, so no vertex but the laser's ends a single drawn edge
    assert not loose, "a drawn edge ends in nothing: %s" % [
        "frame %d vertex %d edge %s faces %s shown %s" % (
            fr, v, es, [EDGE_FACES[e] for e in es], [f for f in range(13) if fv[f]])
        for fr, v, es, fv in loose[:6]]
    flick = [(e, i) for e in range(38) for i in range(1, len(vis) - 1)
             if e in vis[i - 1] and e in vis[i + 1] and e not in vis[i]]
    assert not flick, "edges flicker in the tumble:\n" + "\n".join(
        "  edge %d frame %d: faces %d and %d, (Mn)z - T %s and %s" % (
            e, i, EDGE_FACES[e][0], EDGE_FACES[e][1],
            [qs[j][EDGE_FACES[e][0]] for j in range(i - 2, i + 3)],
            [qs[j][EDGE_FACES[e][1]] for j in range(i - 2, i + 3)])
        for e, i in flick[:16])
    xs, ys = [], []
    for ya in range(0, SINES, SINES // 16):
        for pa in range(0, SINES, SINES // 16):
            for ra in range(0, SINES, SINES // 16):
                m = matrix(ya, pa, ra)
                pts = project(m)
                xs += [p[0] for p in pts]
                ys += [p[1] for p in pts]
                P = [tuple(sum(m[r][j] * v[j] for j in range(3)) for r in range(3)) for v in V]
                for (a, b, c), t, q in zip(tris, scr, facing(m)):
                    ar = area4(pts, t)
                    if (ar > 0) != (q < 0):
                        sure = max(sure, abs(ar))
                    nn = _cross(_sub(P[b], P[a]), _sub(P[c], P[a]))
                    e = _sub(eye, P[a])
                    cosv = _dot(nn, e) / math.sqrt(_dot(nn, nn) * _dot(e, e))
                    if (cosv > 0) != (q < 0):
                        tilt = max(tilt, math.degrees(math.asin(abs(cosv))))
    assert sure <= SURE, "a face disagrees with its triangle on the screen at area %d" % sure
    assert tilt <= EDGEON, "a face disagrees with its plane %.2f degrees off edge-on" % tilt
    return dict(V=V, scr=scr, fn=fn, sn=sn, rz=rz, vis=vis, pix=pix, xs=xs, ys=ys,
                sure=sure, tilt=tilt, agree=agree, matrix=matrix, project=project)


# ------------------------------------------------------ COBRA 2's sky
#
# **The camera circles the ship, and the ship flies straight** (D106).
# The ship does not turn in the world, so its frame is the world's, and
# the rotation Transform uses is the camera's: a star -- a direction --
# goes through it as a vertex does, and a speck of dust -- a point near
# the ship -- goes through it too and slides one unit a frame back along
# the ship's length, which is the ship flying. What is on the screen is
# recycled the way Elite recycles its stardust: one that leaves is put
# back into view, through the matrix's transpose, and from then on it is
# fixed in the world again.

ERR = 2.5                    # the sky's fixed point against division, pixels: 2.16 measured, a whole one of it the floor to a pixel


def star_table():
    """srz: a star's Z >> 6 to 512 * 16 * FOCAL / Z, for the offset
    ((|X| >> 4) * r) >> 9; zero where that is past a byte, a Z too far
    off the axis for the screen anyway"""
    t = []
    for i in range(256):
        r = int(round(512.0 * 16 * FOCAL / (64 * i + 32)))
        t.append(r if r <= 255 else 0)
    return t


def dust_table():
    """drz: a speck's Z >> 7, plus 256, to 128 * FOCAL / depth for the
    offset ((|X| >> 5) * r) >> 8 -- a speck's unit is two model units, so
    a bin is two deep from DIST -- and zero outside DNEAR..DFAR"""
    t = []
    for i in range(512):
        depth = DIST + 2 * (i - 256) + 1
        t.append(int(round(128.0 * FOCAL / depth)) if DNEAR <= depth <= DFAR else 0)
    assert max(t) <= 255, "a dust reciprocal outgrew a byte"
    return t


def _rot(m, p):
    return [sum(m[r][j] * p[j] for j in range(3)) for r in range(3)]


def star_screen(m, d, srz):
    """Sky(), a star: its direction through the matrix, and where on the
    screen it lands -- or None"""
    X, Y, Z = _rot(m, d)
    assert abs(Z) < 16384, "a star's Z outgrew its bins"
    if Z < 0 or not srz[Z >> 6]:
        return None
    r = srz[Z >> 6]
    px, py = (abs(X) >> 4) * r, (abs(Y) >> 4) * r
    if px >= 256 * 256 or py >= 240 * 256:
        return None
    ox, oy = px >> 9, py >> 9
    return (CX + ox if X >= 0 else CX - ox, CY - oy if Y >= 0 else CY + oy)


def dust_screen(m, p, drz):
    """Sky(), a speck: where on the screen it lands -- or None -- and
    whether it is near enough to be bright"""
    X, Y, Z = _rot(m, p)
    r = drz[(Z >> 7) + 256]
    if not r:
        return None
    px, py = (abs(X) >> 5) * r, (abs(Y) >> 5) * r
    if px >= 128 * 256 or py >= 120 * 256:
        return None
    ox, oy = px >> 8, py >> 8
    return (CX + ox if X >= 0 else CX - ox, CY - oy if Y >= 0 else CY + oy, r >= DBRIGHT, Z)


def place(m, v):
    """Place(): a view vector back into the world through the matrix's
    transpose, each product brought back by seven bits before the sum so
    none leaves an INT -- or None where a coordinate leaves a byte"""
    a = [((m[0][j] * v[0]) >> 7) + ((m[1][j] * v[1]) >> 7) + ((m[2][j] * v[2]) >> 7)
         for j in range(3)]
    return tuple(a) if all(-127 <= c <= 127 for c in a) else None


def star_view(px, py):
    """StarAt(): the view direction through a point of the screen, px
    right of the centre and py above it, about 110 long"""
    return ((px * 77) >> 8, (py * 77) >> 8, 108)


def dust_view(d, x, y):
    """DustAt(): a point d deep, x right and y up, in model units, as a
    view vector in the dust's units of two"""
    return (x >> 1, y >> 1, (d - DIST) >> 1)


# **Behind the ship, the sky is hidden.** The ship is lines, so a star
# behind it would show through its body; filling it black would cost a
# frame. Its outline is the rim edges -- on both their faces' outlines --
# with one face shown and one not, and a point is behind the ship when it
# is between that outline's crossings of its row. The ship is convex, so a
# row crosses it once.

def rim_edges():
    """rim(): the edges on both their faces' outlines -- all but the
    laser, a spur, and the stern's panels, face 9's on both sides"""
    on = [set() for _ in range(13)]
    for f, lp in enumerate(face_loops()):
        for i in range(len(lp)):
            on[f].add(frozenset((lp[i], lp[(i + 1) % len(lp)])))
    rim = [1 if f1 != f2 and frozenset(EDGES[e]) in on[f1] and frozenset(EDGES[e]) in on[f2] else 0
           for e, (f1, f2) in enumerate(EDGE_FACES)]
    assert sum(rim) == 38 - 14 - 1, "the rim is not every edge but the laser and the stern's panels"
    return rim


def recip_tables():
    """rlo, rhi: 65,536 / dy for dy 1..239, a byte of it each"""
    r = [0] + [min(65535, int(round(65536.0 / dy))) for dy in range(1, 240)]
    return [v & 255 for v in r], [v >> 8 for v in r]


def outline(sil, rlo, rhi):
    """Sky()'s outline, from Visible()'s list of outline edges: each top
    to bottom as yt yb xt xb, whether x falls going down, and its slope
    (|dx| * 65536 / dy) >> 8 -- a level one left out, its ends being its
    neighbours' -- and the box around them"""
    recs, box = [], [255, 0, 255, 0]
    for xa, ya, xb, yb in sil:
        if ya == yb:
            continue
        (xt, yt), (xo, yo) = ((xa, ya), (xb, yb)) if yb > ya else ((xb, yb), (xa, ya))
        box = [min(box[0], xt, xo), max(box[1], xt, xo), min(box[2], yt), max(box[3], yo)]
        dy, adx = yo - yt, abs(xo - xt)
        recs.append((yt, yo, xt, xo, 1 if xo < xt else 0, adx * rhi[dy] + ((adx * rlo[dy]) >> 8)))
    return recs, box


def hidden(recs, box, px, py):
    """Sky()'s .hid: the point is in the outline's box and between its
    crossings of the point's row. An edge has its rows from its top to
    just above its bottom, so a convex outline crosses a row twice, and
    the search stops at the second"""
    if not recs or not (box[0] <= px <= box[1] and box[2] <= py <= box[3]):
        return False
    lo, hi, found = 255, 0, 0
    for yt, yb, xt, xb, sgn, slope in recs:
        if py < yt or py >= yb:
            continue
        k = py - yt
        off = (((k * (slope & 255)) >> 8) + (k * (slope >> 8))) & 255
        x = (xt - off if sgn else xt + off) & 255
        found, lo, hi = found + 1, min(lo, x), max(hi, x)
        if found == 2:
            break
    return found > 0 and lo <= px <= hi


@functools.lru_cache(maxsize=None)
def sky_model():
    """COBRA 2's sky, checked over a grid of poses: stars and specks put
    where the program puts them, then projected as it projects them, and
    each landing within ERR of where exact division puts the same point."""
    srz, drz = star_table(), dust_table()
    matrix = act_model(RATES2, TURNIN2)["matrix"]
    rnd = random.Random(1)
    err_s = err_d = 0.0
    stars = starsin = specks = specksin = 0
    for ya in range(0, SINES, SINES // 8):
        for pa in range(0, SINES, SINES // 8):
            for ra in range(0, SINES, SINES // 8):
                m = matrix(ya, pa, ra)
                for _ in range(8):
                    d = place(m, star_view(rnd.randint(-124, 124), rnd.randint(-116, 116)))
                    assert d is not None, "a star left a byte"
                    stars += 1
                    s = star_screen(m, d, srz)
                    if s:
                        starsin += 1
                        X, Y, Z = _rot(m, d)
                        err_s = max(err_s, abs(s[0] - (CX + FOCAL * X / Z)),
                                    abs(s[1] - (CY - FOCAL * Y / Z)))
                    dd = DNEAR + rnd.randint(0, 511)
                    hx, hy = dd * 45 >> 7, dd * 21 >> 6
                    p = place(m, dust_view(dd, ((rnd.randint(0, 255) - 128) * hx) >> 7,
                                           ((rnd.randint(0, 255) - 128) * hy) >> 7))
                    if p is None:
                        continue
                    specks += 1
                    t = dust_screen(m, p, drz)
                    if t:
                        specksin += 1
                        X, Y, Z = _rot(m, p)
                        dep = DIST + Z / 64.0
                        err_d = max(err_d, abs(t[0] - (CX + FOCAL * X / 64.0 / dep)),
                                    abs(t[1] - (CY - FOCAL * Y / 64.0 / dep)))
    assert err_s <= ERR, "a star is %.2f px from exact" % err_s
    assert err_d <= ERR, "a speck is %.2f px from exact" % err_d
    return dict(srz=srz, drz=drz, err_s=err_s, err_d=err_d, stars=stars, starsin=starsin,
                specks=specks, specksin=specksin)


def act_text(target="cobra"):
    """The block a compiled COBRA compiles behind, and what it reports:
    demos/cobra.act's, or demos/cobra2.act's -- the same model at half
    the tumble, and the sky's two tables."""
    rates = (YAWR, PITCHR, ROLLR) if target == "cobra" else RATES2
    md = act_model(rates, HYST if target == "cobra" else TURNIN2)
    V, fn, sn, rz, vis, pix, xs, ys = (md[k] for k in ("V", "fn", "sn", "rz", "vis", "pix", "xs", "ys"))

    def rows(vals, per):
        return "\n".join("  " + " ".join(str(v) for v in vals[i:i + per])
                         for i in range(0, len(vals), per))

    vb = []
    for v in V:
        lv = (128 * sum(v)) & 0xFFFF
        vb += [v[0] + 128, v[1] + 128, v[2] + 128, lv & 0xFF, lv >> 8]
    nb = []
    for n, T in fn:
        k = (128 * sum(n) + T) & 0xFFFF
        nb += [n[0] + 128, n[1] + 128, n[2] + 128, k & 0xFF, k >> 8]
    o = [ACT_BEGIN,
         "; the Cobra Mk III as bbcelite.com publishes it: 28 vertices, each as",
         "; x+128 y+128 z+128 and the 16-bit 128*(x+y+z) Transform takes back off;",
         "; 128 is 127 here, the one coordinate a signed byte cannot hold",
         "BYTE ARRAY vb(140) = [\n%s]" % rows(vb, 15),
         "; 38 edges: their two vertices, and the two faces they border",
         "BYTE ARRAY ea(38) = [\n%s]" % rows([a for a, _ in EDGES], 19),
         "BYTE ARRAY eb(38) = [\n%s]" % rows([b for _, b in EDGES], 19),
         "BYTE ARRAY ef1(38) = [\n%s]" % rows([a for a, _ in EDGE_FACES], 19),
         "BYTE ARRAY ef2(38) = [\n%s]" % rows([b for _, b in EDGE_FACES], 19),
         "; 13 faces: the normal of each one's own triangle of the vertices above,",
         "; 127 long, as nx+128 ny+128 nz+128 and the 16-bit 128*(nx+ny+nz) + T,",
         "; T being where the rotated normal's z turns the face to the viewer",
         "BYTE ARRAY nb(65) = [\n%s]" % rows(nb, 15),
         "; sine, 127 to a unit, %d steps to a turn: cosine is sn(a + %d)" % (SINES, SINES // 4),
         "INT ARRAY sn(%d) = [\n%s]" % (SINES, rows(sn, 16)),
         "; 256 * FOCAL / depth, for bins two model units deep from DIST - 2 * ZBIAS",
         "BYTE ARRAY rz(%d) = [\n%s]" % (ZBINS, rows(rz, 17)),
         "CONST DIST = %d                     ; the camera, model units from the ship's centre" % DIST,
         "CONST FOCAL = %d" % FOCAL,
         "CONST ZBIAS = %d                     ; Z's high byte plus this is the depth bin" % ZBIAS,
         "CONST CX = %d" % CX,
         "CONST CY = %d" % CY,
         "CONST YAWR = $%04X                  ; the angles' steps a frame" % rates[0],
         "CONST PITCHR = $%04X" % rates[1],
         "CONST ROLLR = $%04X" % rates[2]]
    if target == "cobra2":
        sky = sky_model()
        o += ["; the sky: a star's Z >> 6 to 512 * 16 * FOCAL / Z, zero off the screen's cone",
              "BYTE ARRAY srz(256) = [\n%s]" % rows(sky["srz"], 16),
              "; the dust: a speck's Z >> 7, + 256, to 128 * FOCAL / depth, zero outside %d..%d"
              % (DNEAR, DFAR),
              "BYTE ARRAY drz(512) = [\n%s]" % rows(sky["drz"], 16),
              "; the edges on both their faces' outlines -- all but the laser, a spur,",
              "; and the stern's panels: on the ship's outline when one face is shown",
              "BYTE ARRAY rim(38) = [\n%s]" % rows(rim_edges(), 19),
              "; 65,536 / dy, a byte each: an outline edge's slope is |dx| times it",
              "BYTE ARRAY rlo(240) = [\n%s]" % rows(recip_tables()[0], 16),
              "BYTE ARRAY rhi(240) = [\n%s]" % rows(recip_tables()[1], 16),
              "CONST NS = %d                        ; stars on the screen, each recycled as it leaves" % STARS,
              "CONST ND = %d                        ; specks of dust, likewise" % DUST,
              "CONST DNEAR = %d                    ; the dust's depths, model units" % DNEAR,
              "CONST DFAR = %d" % DFAR,
              "CONST DBRIGHT = %d                  ; a speck with a reciprocal this big is bright" % DBRIGHT]
    o.append(ACT_END)
    counts = [len(v) for v in vis]
    report = [
        "  %s.act: 13 faces culled by their normals -- against their planes, wrong only"
        " %.2f degrees from edge-on; against their triangles on the screen, only below"
        " an area of %d" % (target, md["tilt"], md["sure"]),
        "  on the screen over %d poses: x %d-%d, y %d-%d; reciprocals %d-%d"
        % (len(xs) // 28 + 4096, min(xs), max(xs), min(ys), max(ys), min(rz), max(rz)),
        "  the tumble's first 4,096 frames: %d-%d edges a frame, mean %.1f; %d-%d pixels,"
        " mean %d; no edge flickers" % (min(counts), max(counts), sum(counts) / 4096.0,
                                          min(pix), max(pix), sum(pix) // 4096)]
    if target == "cobra2":
        report.append("  the sky: stars within %.2f px of exact division, dust within %.2f; of"
                      " the points placed in view, %d of %d stars and %d of %d specks land on the"
                      " screen" % (sky["err_s"], sky["err_d"], sky["starsin"], sky["stars"],
                                   sky["specksin"], sky["specks"]))
    return "\n".join(o), report


def splice(text, block):
    a = text.index(ACT_BEGIN)
    b = text.index(ACT_END, a) + len(ACT_END)
    return text[:a] + block + text[b:]


def main():
    check = "--check" in sys.argv
    bas, bas_report = bas_text()
    outs = [(BAS, bas, bas_report)]
    for target, path in (("cobra", ACT), ("cobra2", ACT2)):
        block, report = act_text(target)
        outs.append((path, splice(io.open(path, encoding="utf-8").read(), block), report))
    if check:
        stale = [p for p, text, _ in outs if io.open(p, encoding="utf-8").read() != text]
        for p in stale:
            print("  %s is not what tools/mk3d.py writes: python tools/mk3d.py"
                  % os.path.relpath(p, ROOT))
        if not stale:
            print("  demos/cobra.bas, and cobra.act's and cobra2.act's model blocks, are current")
        return 1 if stale else 0
    for p, text, report in outs:
        io.open(p, "w", encoding="utf-8", newline="\n").write(text)
        for line in report:
            print(line)
    print("  -> %s" % ", ".join(os.path.relpath(p, ROOT) for p, _, _ in outs))
    return 0


if __name__ == "__main__":
    sys.exit(main())
